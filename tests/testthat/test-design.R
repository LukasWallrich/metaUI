test_that("design settings reject malformed or unreadable values", {
  expect_error(app_design(accent = "red"), "six-digit")
  expect_error(app_design(accent = "#FFFFFF"), "contrast")
  expect_error(app_design(text = "#EEEEEE"), "contrast")
  expect_error(app_design(surface = NA_character_), "six-digit")
  expect_error(app_design(font = "Arial; color:red"), "font must")
  expect_error(app_design(text_size = Inf), "finite")
  expect_error(app_design(radius = 17), "radius")
  expect_error(metaUI:::validate_design(list(unknown = 1)), "Unknown design")
  expect_error(metaUI:::validate_design(list(accent = "#096B74", accent = "#096B74")), "named list")
  d <- app_design(accent = "#69429a", font = "georgia", radius = 0)
  expect_identical(d$accent, "#69429A")
  expect_equal(metaUI:::design_contrast("#000000", "#FFFFFF"), 21)
  expect_equal(metaUI:::design_contrast("#FFFFFF", "#000000"), 21)
  expect_equal(metaUI:::design_contrast("#ABCDEF", "#ABCDEF"), 1)
  code <- metaUI:::design_r_code(d)
  env <- new.env()
  eval(parse(text = code), env)
  expect_identical(env$design, d)
  expect_equal(metaUI:::validate_design(jsonlite::fromJSON(jsonlite::toJSON(d, auto_unbox = TRUE))), d)
})

test_that("design exports survive app generation and JSON builds", {
  d <- prepared()
  path <- tempfile("metaui-design-")
  on.exit(unlink(path, recursive = TRUE))
  theme <- app_design(accent = "#69429A", font = "georgia", text_size = 18, spacing = "compact", radius = 0)
  generate_shiny(d, "Designed fixture", design = theme, save_to_folder = path, launch_app = FALSE)
  css <- paste(readLines(file.path(path, "www", "app-design.css")), collapse = "\n")
  expect_match(css, "--metaui-accent:#69429A", fixed = TRUE)
  expect_match(css, "Georgia", fixed = TRUE)
  expect_match(css, "padding:16px", fixed = TRUE)
  expect_match(metaUI:::design_preview(theme), metaUI:::design_css(theme), fixed = TRUE)
  expect_match(paste(readLines(file.path(path, "ui.R")), collapse = "\n"), "app-design.css", fixed = TRUE)
  expect_identical(readRDS(file.path(path, "dataset.rds")), d)
  expect_equal(jsonlite::read_json(file.path(path, "design.json"), simplifyVector = TRUE), theme)
  # Standalone generated scripts must parse, with no dependency on metaUI's namespace.
  for (file in c("ui.R", "server.R", "labels_and_options.R")) expect_no_error(parse(file.path(path, file)))
  expect_match(paste(readLines(file.path(path, "server.R")), collapse = "\n"), 'accent = "#69429A"', fixed = TRUE)
  generate_shiny(d, "Plain fixture", save_to_folder = path, launch_app = FALSE, overwrite = TRUE)
  expect_false(file.exists(file.path(path, "www", "app-design.css")))
  expect_false(grepl("app-design.css", paste(readLines(file.path(path, "ui.R")), collapse = "\n"), fixed = TRUE))
  bad <- tempfile("invalid-design-")
  expect_error(generate_shiny(d, "Bad", design = list(accent = "#FFFFFF"), save_to_folder = bad, launch_app = FALSE), "contrast")
  expect_false(dir.exists(bad))
  cfg <- jsonlite::read_json(system.file("examples", "tiny.json", package = "metaUI"))
  cfg$data <- system.file("examples", "tiny.csv", package = "metaUI")
  cfg$output <- file.path(path, "json-app"); cfg$design <- theme
  build_app(cfg)
  expect_equal(jsonlite::read_json(file.path(cfg$output, "design.json"), simplifyVector = TRUE), theme)
})

test_that("helper refuses invalid exports and recovers after correction", {
  app <- design_app()
  shiny::testServer(app, {
    session$setInputs(accent = "#69429A", font = "georgia", text_size = 18, spacing = "compact", radius = 0)
    expect_match(output$r_code, '#69429A', fixed = TRUE)
    expect_equal(valid_design()$text_size, 18)
    good <- valid_design()
    session$setInputs(accent = "#FFFFFF")
    expect_match(output$contrast, "contrast")
    expect_error(output$r_code, "contrast")
    expect_identical(last_valid(), good)
    session$setInputs(accent = "#235A97")
    expect_match(output$r_code, '#235A97', fixed = TRUE)
  })
})

test_that("dark palettes keep the forest labels on the selected surface", {
  d <- app_design(accent = "#90CAF9", text = "#F7F9FC", background = "#131C27", surface = "#202C3A")
  rows <- data.frame(es = .2, LCL = .1, UCL = .3, row = 1, label = "Example", kind = "Selected effect")
  plot <- metaUI:::metaUI_forest_plot(rows, "SMD", accent = d$accent, ink = d$text, background = d$surface)
  expect_equal(plot$theme$plot.background$fill, d$surface)
  expect_equal(plot$theme$axis.text$colour, d$text)
  expect_equal(plot$data$es, rows$es)
  expect_true(all(metaUI:::design_contrasts(d) >= 4.5))
})
